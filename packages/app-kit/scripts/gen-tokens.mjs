// Generates src/tokens/generated.ts from tokens/tokens.json (copy of the lab's system/tokens/tokens.json).
// One flat map per theme × language: keys use the Figma path ("color/text/content/default").
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = JSON.parse(readFileSync(join(root, '../../design/tokens/tokens.json'), 'utf8'));

const flat = {}; // dotted path -> { value, type, modes }
function walk(node, path, type) {
  if (node && typeof node === 'object' && !Array.isArray(node)) {
    const t = node.$type ?? type;
    if ('$value' in node) {
      flat[path.join('.')] = { value: node.$value, type: t, modes: node.$extensions?.['design-flow']?.modes ?? {} };
      return;
    }
    for (const [k, v] of Object.entries(node)) if (!k.startsWith('$')) walk(v, [...path, k], t);
  }
}
for (const tier of ['primitive', 'brand', 'semantic', 'component']) walk(src[tier], [tier], undefined);

const MODES = { light_en: ['light', 'en'], light_ar: ['light', 'ar'], dark_en: ['dark', 'en'], dark_ar: ['dark', 'ar'] };

function pick(tok, modes) {
  for (const m of modes) if (tok.modes[m] !== undefined) return tok.modes[m];
  return tok.value;
}
function resolve(value, modes, seen = []) {
  if (typeof value === 'string') {
    const whole = value.match(/^\{([^}]+)\}$/);
    if (whole) {
      const ref = whole[1];
      if (seen.includes(ref)) throw new Error('cycle ' + seen.join(' > '));
      const tok = flat[ref];
      if (!tok) throw new Error('missing ref ' + ref);
      return resolve(pick(tok, modes), modes, [...seen, ref]);
    }
    return value;
  }
  if (Array.isArray(value)) return value.map((v) => resolve(v, modes, seen));
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, resolve(v, modes, seen)]));
  return value;
}
const px = (v) => (typeof v === 'string' && /^-?[\d.]+px$/.test(v) ? parseFloat(v) : v);
const ms = (v) => (typeof v === 'string' && /^[\d.]+ms$/.test(v) ? parseFloat(v) : v);

const out = {};
for (const [name, modes] of Object.entries(MODES)) {
  const map = {};
  for (const [path, tok] of Object.entries(flat)) {
    if (!path.startsWith('semantic.') && !path.startsWith('component.')) continue; // apps bind semantic + component only
    let v = resolve(pick(tok, modes), modes);
    if (tok.type === 'shadow') v = Object.fromEntries(Object.entries(v).map(([k, x]) => [k, px(x)]));
    else v = ms(px(v));
    map[path.split('.').slice(1).join('/')] = v;
  }
  out[name] = map;
}
const header = '// GENERATED by scripts/gen-tokens.mjs from tokens/tokens.json. Do not edit.\n';
writeFileSync(join(root, 'src/tokens/generated.ts'), header + 'export const tokenSets = ' + JSON.stringify(out, null, 1) + ' as const;\n');
console.log('tokens:', Object.keys(out).map((k) => `${k} ${Object.keys(out[k]).length}`).join(', '));
